"""UE5.7 C++ scaffolding adapter — emits a real compiling Unreal project.

This adapter replaces the minimal `.uproject`-only scaffold with a full UE 5.7
C++ project that compiles against the locally installed engine via
`UnrealBuildTool` / `Build.bat`. It mirrors the structure of the shipped
`TP_Blank` template (which was read off this machine's install) and extends it
with gameplay classes (GameMode, Character, PlayerController, HUD) derived from
the GameBrief.

Files written (engine="ue5", module name derived from title slug):
    <Proj>/<Proj>.uproject                 — EngineAssociation="5.7", module + plugin list
    <Proj>/Source/<Mod>/<Mod>.Build.cs      — ModuleRules, V6 build settings
    <Proj>/Source/<Mod>Target.Target.cs      — Game target, Unreal5_7 include order
    <Proj>/Source/<Mod>EditorTarget.Target.cs — Editor target
    <Proj>/Source/<Mod>/<Mod>.h + .cpp      — IMPLEMENT_PRIMARY_GAME_MODULE
    <Proj>/Source/<Mod>/<Mod>GameMode.h/.cpp
    <Proj>/Source/<Mod>/<Mod>Character.h/.cpp
    <Proj>/Source/<Mod>/<Mod>PlayerController.h/.cpp
    <Proj>/Source/<Mod>/<Mod>HUD.h/.cpp
    <Proj>/Config/DefaultEngine.ini          — DX12, 8K scalability, audio
    <Proj>/Config/DefaultGame.ini
    <Proj>/Config/DefaultInput.ini           — Enhanced Input
    <Proj>/Content/                          — asset target dir
    <Proj>/README.md

All C++ is valid against UE 5.7 API (Core, CoreUObject, Engine, InputCore,
EnhancedInput, SlateUI). The project builds with:
    "<UE5>/Engine/Build/BatchFiles/Build.bat" <Mod>Editor Win64 Development -Project="<Proj>/<Proj>.uproject"
"""
