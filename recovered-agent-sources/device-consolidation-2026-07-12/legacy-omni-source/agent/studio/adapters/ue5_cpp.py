def _character_cpp(mod: str) -> str:
    cls = f"A{mod}Character"
    return f"""// Generated by Axiom Studio — UE5.7 C++ scaffold
#include "{mod}Character.h"
#include "Components/CapsuleComponent.h"
#include "GameFramework/SpringArmComponent.h"
#include "Camera/CameraComponent.h"
#include "GameFramework/Controller.h"
#include "EnhancedInputComponent.h"
#include "EnhancedInputSubsystems.h"

{cls}::{cls}()
{{
    // Set size for collision capsule
    GetCapsuleComponent()->InitCapsuleSize(42.f, 96.0f);

    // Don't rotate when the controller rotates
    bUseControllerRotationPitch = false;
    bUseControllerRotationYaw = false;
    bUseControllerRotationRoll = false;

    // Camera boom (third person)
    CameraBoom = CreateDefaultSubobject<USpringArmComponent>(TEXT("CameraBoom"));
    CameraBoom->SetupAttachment(RootComponent);
    CameraBoom->TargetArmLength = 400.0f;
    CameraBoom->bUsePawnControlRotation = true;

    // Follow camera
    FollowCamera = CreateDefaultSubobject<UCameraComponent>(TEXT("FollowCamera"));
    FollowCamera->SetupAttachment(CameraBoom, USpringArmComponent::SocketName);
    FollowCamera->bUsePawnControlRotation = false;
}}

void {cls}::BeginPlay()
{{
    Super::BeginPlay();

    // Add the input mapping context
    if (APlayerController* PlayerController = Cast<APlayerController>(Controller))
    {{
        if (UEnhancedInputLocalPlayerSubsystem* Subsystem =
            ULocalPlayer::GetSubsystem<UEnhancedInputLocalPlayerSubsystem>(
                PlayerController->GetLocalPlayer()))
        {{
            Subsystem->AddMappingContext(DefaultMappingContext, 0);
        }}
    }}
}}

void {cls}::SetupPlayerInputComponent(UInputComponent* PlayerInputComponent)
{{
    if (UEnhancedInputComponent* EnhancedInputComponent =
        Cast<UEnhancedInputComponent>(PlayerInputComponent))
    {{
        EnhancedInputComponent->BindAction(MoveAction, ETriggerEvent::Triggered, this, &{cls}::Move);
        EnhancedInputComponent->BindAction(LookAction, ETriggerEvent::Triggered, this, &{cls}::Look);
    }}
    else
    {{
        Super::SetupPlayerInputComponent(PlayerInputComponent);
    }}
}}

void {cls}::Move(const FInputActionValue& Value)
{{
    const FVector2D MovementVector = Value.Get<FVector2D>();
    if (Controller != nullptr)
    {{
        const FRotator Rotation = Controller->GetControlRotation();
        const FRotator YawRotation(0, Rotation.Yaw, 0);
        const FVector ForwardDirection = FRotationMatrix(YawRotation).GetUnitAxis(EAxis::X);
        const FVector RightDirection = FRotationMatrix(YawRotation).GetUnitAxis(EAxis::Y);
        AddMovementInput(ForwardDirection, MovementVector.Y);
        AddMovementInput(RightDirection, MovementVector.X);
    }}
}}

void {cls}::Look(const FInputActionValue& Value)
{{
    const FVector2D LookAxisVector = Value.Get<FVector2D>();
    if (Controller != nullptr)
    {{
        AddControllerYawInput(LookAxisVector.X);
        AddControllerPitchInput(LookAxisVector.Y);
    }}
}}
"""


