# ── .uproject ──────────────────────────────────────────────────────────

def _uproject(mod: str, title: str, description: str, plugin_list: List[str]) -> str:
    plugins = [
        {"Name": p, "Enabled": True, "TargetAllowList": ["Editor"]} for p in plugin_list
    ]
    return json.dumps({
        "FileVersion": 3,
        "EngineAssociation": UE5_ENGINE_ASSOCIATION,
        "Category": "AAA",
        "Description": (description or f"{title} — built by Axiom Studio")[:500],
        "Modules": [
            {"Name": mod, "Type": "Runtime", "LoadingPhase": "Default"}
        ],
        "Plugins": plugins,
    }, indent=4)


# ── The adapter ────────────────────────────────────────────────────────

class UE5CppAdapter(Adapter):
    """Scaffold a real compiling Unreal Engine 5.7 C++ project.

    Always available (local scaffolding, no keys). Triggers a real UBT
    compile at build time if ``UE5_BUILD_ON_SCAFFOLD=1`` is set.
    """
    capability = "engine_project"
    provider = Provider.UE5
    requires_env: List[str] = []  # local
    est_unit_cost_usd = 0.0

    def available(self) -> bool:
        return True  # scaffolding is always available

    def _real(self, prompt: str, workdir: Path, **kwargs) -> Tuple[List[str], str]:
        engine = kwargs.get("engine", "ue5")
        if engine != "ue5":
            # Fall back to the legacy minimal scaffold for non-UE5 engines
            return self._legacy_scaffold(prompt, workdir, **kwargs)

        return self._scaffold_ue5(prompt, workdir, **kwargs)

    def _scaffold_ue5(self, prompt: str, workdir: Path,
                      **kwargs) -> Tuple[List[str], str]:
        title = kwargs.get("title", "AxiomGame")
        mod = _slug(title)
        proj_id = _upid(title)
        proj_dir = workdir / "ue5_project" / proj_id
        src_dir = proj_dir / "Source" / mod

        # Create directory tree
        (proj_dir / "Content").mkdir(parents=True, exist_ok=True)
        (proj_dir / "Config").mkdir(parents=True, exist_ok=True)
        (proj_dir / "Source").mkdir(parents=True, exist_ok=True)
        src_dir.mkdir(parents=True, exist_ok=True)

        artifacts: List[str] = []

        def _write(rel: str, content: str) -> None:
            p = proj_dir / rel
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(content, encoding="utf-8")
            artifacts.append(str(p))

        # — .uproject —
        plugins = kwargs.get("plugins", ["ModelingToolsEditorMode"])
        _write(f"{proj_id}.uproject",
               _uproject(mod, title, prompt, plugins))

        # — Target files —
        _write(f"Source/{mod}Target.Target.cs", _game_target(mod))
        _write(f"Source/{mod}EditorTarget.Target.cs", _editor_target(mod))

        # — Build.cs —
        _write(f"Source/{mod}/{mod}.Build.cs", _build_cs(mod))

        # — Module primary files —
        _write(f"Source/{mod}/{mod}.h", _module_header(mod))
        _write(f"Source/{mod}/{mod}.cpp", _module_cpp(mod))

        # — Gameplay classes —
        _write(f"Source/{mod}/{mod}GameMode.h", _game_mode_header(mod))
        _write(f"Source/{mod}/{mod}GameMode.cpp", _game_mode_cpp(mod))
        _write(f"Source/{mod}/{mod}Character.h", _character_header(mod))
        _write(f"Source/{mod}/{mod}Character.cpp", _character_cpp(mod))
        _write(f"Source/{mod}/{mod}PlayerController.h", _pc_header(mod))
        _write(f"Source/{mod}/{mod}PlayerController.cpp", _pc_cpp(mod))
        _write(f"Source/{mod}/{mod}HUD.h", _hud_header(mod))
        _write(f"Source/{mod}/{mod}HUD.cpp", _hud_cpp(mod))

        # — Config —
        _write("Config/DefaultEngine.ini", _default_engine_ini(mod))
        _write("Config/DefaultGame.ini", _default_game_ini(mod))
        _write("Config/DefaultInput.ini", _default_input_ini(mod))

        # — README with build instructions —
        build_cmd = (
            f'"{UE5_ENGINE_ROOT}\\Engine\\Build\\BatchFiles\\Build.bat" '
            f"{mod}Editor Win64 Development "
            f'-Project="{proj_dir / (proj_id + ".uproject")}"'
        )
        uproject_path = str(proj_dir / (proj_id + ".uproject"))
        editor_exe = UE5_ENGINE_ROOT + r"\Engine\Binaries\Win64\UnrealEditor.exe"
        readme = (
            f"# {title}\n\n"
            f"Real UE 5.7 C++ project — scaffolded by **Axiom Studio**.\n\n"
            f"## Module\n`{mod}`\n\n"
            f"## Classes\n"
            f"- `{mod}GameMode` — game mode (default pawn + HUD wiring)\n"
            f"- `{mod}Character` — third-person character, Enhanced Input\n"
            f"- `{mod}PlayerController` — player controller\n"
            f"- `{mod}HUD` — Slate crosshair + status display\n\n"
            f"## Build (from terminal)\n```bat\n{build_cmd}\n```\n\n"
            f"## Open in editor\n```bat\n"
            f'"{editor_exe}" "{uproject_path}"\n'
            f"```\n\n"
            f"## Brief\n{prompt}\n"
        )
        _write("README.md", readme)

        # Optionally compile immediately
        built = False
        if os.environ.get("UE5_BUILD_ON_SCAFFOLD", "").strip().lower() in (
            "1", "true", "yes", "on"
        ):
            built = self._try_compile(proj_dir, proj_id, mod)

        notes = f"UE5.7 C++ project scaffolded ({len(artifacts)} files, module={mod})"
        if built:
            notes += " + COMPILED OK"
        return artifacts, notes

    def _legacy_scaffold(self, prompt: str, workdir: Path,
                          **kwargs) -> Tuple[List[str], str]:
        """Minimal scaffold for non-UE5 engines (Unity / Godot)."""
        engine = kwargs.get("engine", "ue5")
        proj = workdir / f"{engine}_project"
        proj.mkdir(parents=True, exist_ok=True)
        (proj / "README.md").write_text(
            f"# {kwargs.get('title', 'Game')} ({engine})\n\n{prompt}\n",
            encoding="utf-8",
        )
        return [str(proj)], f"{engine} legacy scaffold"

    def _try_compile(self, proj_dir: Path, proj_id: str, mod: str) -> bool:
        """Attempt a real UBT compile. Returns True on success."""
        import subprocess
        build_bat = f"{UE5_ENGINE_ROOT}\\Engine\\Build\\BatchFiles\\Build.bat"
        if not Path(build_bat).is_file():
            return False
        proj_path = proj_dir / f"{proj_id}.uproject"
        cmd = [
            build_bat,
            f"{mod}Editor",
            "Win64",
            "Development",
            f'-Project="{proj_path}"',
        ]
        try:
            result = subprocess.run(
                cmd,
                capture_output=True,
                timeout=1800,
            )
            return result.returncode == 0
        except Exception:
            return False


