def _slug(title: str) -> str:
    """UE module name: PascalCase, alphanumeric, no leading digit."""
    s = "".join(c if c.isalnum() else " " for c in title)
    parts = [p for p in s.split() if p]
    mod = "".join(p[:1].upper() + p[1:] for p in parts) if parts else "Game"
    mod = re.sub(r"[^A-Za-z0-9]", "", mod)
    if mod and mod[0].isdigit():
        mod = "G" + mod
    return mod or "Game"


def _upid(title: str) -> str:
    """Lowercase project folder name."""
    return _slug(title)


