create or replace function public.universe_is_active_member(p_realm_id text)
returns boolean
language sql
stable
security definer
set search_path = pg_catalog, public
as $$
  select auth.uid() is not null and exists (
    select 1
    from public.universe_memberships membership
    where membership.realm_id = p_realm_id
      and membership.user_id = auth.uid()
      and membership.status = 'active'
  );
$$;

