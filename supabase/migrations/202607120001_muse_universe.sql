create or replace function public.execute_universe_command(p_command jsonb)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public, extensions
as $$
declare
  v_user_id uuid := auth.uid();
  v_command_id text;
  v_command_type text;
  v_realm_id text;
  v_stream_id text;
  v_stream_type text;
  v_event_type text;
  v_required_scope text;
  v_approval_required boolean;
  v_public_capable boolean;
  v_simulation_forbidden boolean;
  v_expected_version bigint;
  v_current_version bigint := 0;
  v_payload jsonb;
  v_current_entity jsonb := '{}'::jsonb;
  v_entity jsonb;
  v_event jsonb;
  v_result jsonb;
  v_stored_result jsonb;
  v_stored_fingerprint text;
  v_stored_actor uuid;
  v_command_fingerprint text;
  v_actor_id text;
  v_membership_id text;
  v_membership_status text;
  v_scopes text[] := array[]::text[];
  v_is_owner boolean := false;
  v_realm_public boolean := false;
  v_current_public boolean := false;
  v_is_public boolean := false;
  v_simulation boolean := false;
  v_needs_approval boolean := false;
  v_approval_id text;
  v_subject_hash text;
  v_causation_id text;
  v_correlation_id text;
  v_event_id text := gen_random_uuid()::text;
  v_sequence bigint;
  v_occurred_at timestamptz := clock_timestamp();
  v_authorization jsonb;
  v_provenance jsonb;
  v_target_user_id uuid;
  v_target_player_id text;
  v_target_scopes text[];
  v_rows integer;
begin
  if v_user_id is null then
    raise exception using errcode = 'P0001', message = 'universe_unauthorized';
  end if;
  if p_command is null or jsonb_typeof(p_command) <> 'object' then
    raise exception using errcode = 'P0001', message = 'universe_invalid_command';
  end if;
  if pg_column_size(p_command) > 65536
    or not (p_command ?& array[
      'command_id', 'command_type', 'realm_id', 'stream_id',
      'expected_version', 'payload'
    ])
  then
    raise exception using errcode = 'P0001', message = 'universe_invalid_command';
  end if;
  if p_command ? 'actor_id' then
    raise exception using
      errcode = 'P0001',
      message = 'universe_invalid_command',
      detail = 'MUSE_ACTOR_MISMATCH';
  end if;
  if p_command ?| array[
    'authorization', 'owner_authorization', 'provenance',
    'roles', 'scopes', 'stream_type'
  ] then
    raise exception using errcode = 'P0001', message = 'universe_invalid_command';
  end if;
  if exists (
    select 1
    from jsonb_object_keys(p_command) as field(key)
    where not (field.key = any (array[
      'command_id', 'command_type', 'realm_id', 'stream_id',
      'expected_version', 'payload', 'causation_id', 'correlation_id',
      'approval_id', 'simulation'
    ]::text[]))
  ) then
    raise exception using errcode = 'P0001', message = 'universe_invalid_command';
  end if;

  v_command_id := p_command ->> 'command_id';
  v_command_type := p_command ->> 'command_type';
  v_realm_id := p_command ->> 'realm_id';
  v_stream_id := p_command ->> 'stream_id';
  if jsonb_typeof(p_command -> 'command_id') <> 'string'
    or jsonb_typeof(p_command -> 'command_type') <> 'string'
    or jsonb_typeof(p_command -> 'realm_id') <> 'string'
    or jsonb_typeof(p_command -> 'stream_id') <> 'string'
    or v_command_id is null or v_command_id !~ '^[A-Za-z0-9][A-Za-z0-9._:-]{0,127}$'
    or v_realm_id is null or v_realm_id !~ '^[A-Za-z0-9][A-Za-z0-9._:-]{0,127}$'
    or v_stream_id is null or v_stream_id !~ '^[A-Za-z0-9][A-Za-z0-9._:-]{0,127}$'
  then
    raise exception using errcode = 'P0001', message = 'universe_invalid_command';
  end if;
  if p_command ? 'causation_id' and jsonb_typeof(p_command -> 'causation_id') <> 'string'
    or p_command ? 'correlation_id' and jsonb_typeof(p_command -> 'correlation_id') <> 'string'
    or p_command ? 'approval_id' and jsonb_typeof(p_command -> 'approval_id') <> 'string'
  then
    raise exception using errcode = 'P0001', message = 'universe_invalid_command';
  end if;
  v_causation_id := coalesce(nullif(p_command ->> 'causation_id', ''), v_command_id);
  v_correlation_id := coalesce(nullif(p_command ->> 'correlation_id', ''), v_command_id);
  v_approval_id := nullif(p_command ->> 'approval_id', '');
  if v_causation_id !~ '^[A-Za-z0-9][A-Za-z0-9._:-]{0,127}$'
    or v_correlation_id !~ '^[A-Za-z0-9][A-Za-z0-9._:-]{0,127}$'
    or (v_approval_id is not null and v_approval_id !~ '^[A-Za-z0-9][A-Za-z0-9._:-]{0,127}$')
  then
    raise exception using errcode = 'P0001', message = 'universe_invalid_command';
  end if;
  if jsonb_typeof(p_command -> 'expected_version') <> 'number'
    or (p_command ->> 'expected_version') !~ '^(0|[1-9][0-9]*)$'
    or char_length(p_command ->> 'expected_version') > 16
  then
    raise exception using errcode = 'P0001', message = 'universe_invalid_command';
  end if;
  v_expected_version := (p_command ->> 'expected_version')::bigint;
  if v_expected_version > 9007199254740991 then
    raise exception using errcode = 'P0001', message = 'universe_invalid_command';
  end if;
  if jsonb_typeof(p_command -> 'payload') <> 'object'
    or public.universe_json_has_forbidden_keys(p_command -> 'payload')
  then
    raise exception using errcode = 'P0001', message = 'universe_invalid_command';
  end if;
  v_payload := p_command -> 'payload';
  if v_payload ? 'id' and (jsonb_typeof(v_payload -> 'id') <> 'string' or v_payload ->> 'id' <> v_stream_id) then
    raise exception using errcode = 'P0001', message = 'universe_invalid_command';
  end if;
  if v_payload ? 'deleted' and jsonb_typeof(v_payload -> 'deleted') <> 'boolean' then
    raise exception using errcode = 'P0001', message = 'universe_invalid_command';
  end if;
  if p_command ? 'simulation' and jsonb_typeof(p_command -> 'simulation') <> 'boolean' then
    raise exception using errcode = 'P0001', message = 'universe_invalid_command';
  end if;
  v_simulation := coalesce((p_command ->> 'simulation')::boolean, false);

  select spec.stream_type, spec.event_type, spec.required_scope,
         spec.approval_required, spec.public_capable, spec.simulation_forbidden
    into v_stream_type, v_event_type, v_required_scope,
         v_approval_required, v_public_capable, v_simulation_forbidden
  from public.universe_command_spec(v_command_type) as spec;
  if not found then
    raise exception using errcode = 'P0001', message = 'universe_invalid_command';
  end if;
  if v_command_type = 'realm.create' and v_stream_id <> v_realm_id then
    raise exception using errcode = 'P0001', message = 'universe_invalid_command';
  end if;
  if v_simulation and v_simulation_forbidden then
    raise exception using errcode = 'P0001', message = 'universe_forbidden';
  end if;

  v_command_fingerprint := encode(
    digest(convert_to(p_command::text, 'UTF8'), 'sha256'),
    'hex'
  );
  perform pg_advisory_xact_lock(
    hashtextextended('universe-command:' || v_realm_id || ':' || v_command_id, 0)
  );
  select command.result, command.command_fingerprint, command.actor_user_id
    into v_stored_result, v_stored_fingerprint, v_stored_actor
  from public.universe_command_results command
  where command.realm_id = v_realm_id and command.command_id = v_command_id;
  if found then
    if v_stored_fingerprint <> v_command_fingerprint or v_stored_actor <> v_user_id then
      raise exception using errcode = 'P0001', message = 'universe_command_id_conflict';
    end if;
    select realm.owner_user_id = v_user_id
      into v_is_owner
    from public.universe_realms realm
    where realm.realm_id = v_realm_id;
    if not found then
      raise exception using errcode = 'P0001', message = 'universe_not_found';
    end if;
    if not v_is_owner then
      select membership.status, membership.scopes
        into v_membership_status, v_scopes
      from public.universe_memberships membership
      where membership.realm_id = v_realm_id
        and membership.user_id = v_user_id;
      if not found or v_membership_status <> 'active' then
        raise exception using errcode = 'P0001', message = 'universe_forbidden';
      end if;
      if v_command_type <> 'membership.accept'
        and not (v_required_scope = any (v_scopes))
      then
        raise exception using errcode = 'P0001', message = 'universe_forbidden';
      end if;
    end if;
    return jsonb_set(v_stored_result, '{idempotent_replay}', 'true'::jsonb, true);
  end if;

  perform pg_advisory_xact_lock(
    hashtextextended('universe-stream:' || v_stream_type || ':' || v_stream_id, 0)
  );
  select projection.version, projection.entity, projection.is_public
    into v_current_version, v_current_entity, v_current_public
  from public.universe_entities projection
  where projection.realm_id = v_realm_id
    and projection.entity_type = v_stream_type
    and projection.entity_id = v_stream_id
  for update;
  if not found then
    v_current_version := 0;
    v_current_entity := '{}'::jsonb;
    v_current_public := false;
  end if;
  if v_current_version <> v_expected_version then
    raise exception using
      errcode = 'P0001',
      message = 'universe_version_conflict',
      detail = jsonb_build_object(
        'error', 'MUSE_VERSION_CONFLICT',
        'expected_version', v_expected_version,
        'current_version', v_current_version
      )::text;
  end if;

  if v_command_type = 'realm.create' then
    if v_expected_version <> 0 or exists (
      select 1 from public.universe_realms realm where realm.realm_id = v_realm_id
    ) then
      raise exception using
        errcode = 'P0001',
        message = 'universe_version_conflict',
        detail = jsonb_build_object(
          'error', 'MUSE_VERSION_CONFLICT',
          'expected_version', v_expected_version,
          'current_version', 1
        )::text;
    end if;
    if jsonb_typeof(v_payload -> 'mode') <> 'string'
      or jsonb_typeof(v_payload -> 'name') <> 'string'
      or coalesce(v_payload ->> 'mode', '') not in ('private', 'team', 'network', 'public')
      or char_length(coalesce(v_payload ->> 'name', '')) not between 1 and 200
      or exists (
        select 1
        from jsonb_object_keys(v_payload) as field(key)
        where not (field.key = any (array['id', 'name', 'mode', 'visibility']::text[]))
      )
    then
      raise exception using errcode = 'P0001', message = 'universe_invalid_command';
    end if;
    v_actor_id := 'ply_' || gen_random_uuid()::text;
    v_scopes := array['*']::text[];
    v_is_owner := true;
    v_realm_public := (v_payload ->> 'mode') = 'public';
    v_is_public := v_realm_public;
    v_payload := v_payload || jsonb_build_object('owner_id', v_actor_id);
    insert into public.universe_realms (
      realm_id, owner_user_id, name, mode, is_public, version, metadata,
      created_at, updated_at
    ) values (
      v_realm_id, v_user_id, v_payload ->> 'name', v_payload ->> 'mode',
      v_realm_public, 1, v_payload, v_occurred_at, v_occurred_at
    );
    insert into public.universe_memberships (
      realm_id, user_id, membership_id, player_id, status, scopes, metadata,
      created_at, updated_at
    ) values (
      v_realm_id, v_user_id, 'mbr_' || gen_random_uuid()::text,
      v_actor_id, 'active', v_scopes, '{}'::jsonb,
      v_occurred_at, v_occurred_at
    );
  else
    select realm.owner_user_id = v_user_id, realm.is_public
      into v_is_owner, v_realm_public
    from public.universe_realms realm
    where realm.realm_id = v_realm_id
    for update;
    if not found then
      raise exception using errcode = 'P0001', message = 'universe_not_found';
    end if;

    select membership.membership_id, membership.player_id,
           membership.status, membership.scopes
      into v_membership_id, v_actor_id, v_membership_status, v_scopes
    from public.universe_memberships membership
    where membership.realm_id = v_realm_id and membership.user_id = v_user_id
    for update;
    if not found then
      if v_is_owner then
        v_actor_id := v_user_id::text;
        v_membership_status := 'active';
        v_scopes := array['*']::text[];
      else
        raise exception using errcode = 'P0001', message = 'universe_forbidden';
      end if;
    end if;
    if v_command_type = 'membership.accept' then
      if v_membership_status <> 'invited' or v_membership_id <> v_stream_id then
        raise exception using errcode = 'P0001', message = 'universe_forbidden';
      end if;
      v_scopes := array_append(v_scopes, 'membership:accept');
    elsif v_membership_status <> 'active' then
      raise exception using errcode = 'P0001', message = 'universe_forbidden';
    end if;
    if not ('*' = any (v_scopes) or v_required_scope = any (v_scopes)) then
      raise exception using errcode = 'P0001', message = 'universe_forbidden';
    end if;

    v_is_public := v_public_capable and coalesce(v_payload ->> 'visibility', '') = 'public';
    if v_is_public and not v_realm_public then
      raise exception using errcode = 'P0001', message = 'universe_forbidden';
    end if;
    if v_is_public and v_current_version > 0 and not v_current_public then
      raise exception using errcode = 'P0001', message = 'universe_forbidden';
    end if;
    v_needs_approval := v_approval_required or v_is_public;
    if v_needs_approval then
      if v_approval_id is null then
        raise exception using errcode = 'P0001', message = 'universe_forbidden';
      end if;
      v_subject_hash := encode(
        digest(convert_to(v_payload::text, 'UTF8'), 'sha256'),
        'hex'
      );
      perform 1
      from public.universe_approval_grants approval
      where approval.approval_id = v_approval_id
        and approval.realm_id = v_realm_id
        and approval.actor_user_id = v_user_id
        and approval.action = v_command_type
        and approval.correlation_id = v_correlation_id
        and approval.subject_hash = v_subject_hash
        and approval.state = 'approved'
        and approval.expires_at > v_occurred_at
      for update;
      if not found then
        raise exception using errcode = 'P0001', message = 'universe_forbidden';
      end if;
      update public.universe_approval_grants
      set state = 'consumed', consumed_at = v_occurred_at
      where approval_id = v_approval_id;
    end if;

    if v_command_type = 'membership.invite' then
      if not (v_payload ? 'user_id')
        or jsonb_typeof(v_payload -> 'user_id') <> 'string'
        or jsonb_typeof(v_payload -> 'player_id') <> 'string'
      then
        raise exception using errcode = 'P0001', message = 'universe_invalid_command';
      end if;
      begin
        v_target_user_id := (v_payload ->> 'user_id')::uuid;
      exception when invalid_text_representation then
        raise exception using errcode = 'P0001', message = 'universe_invalid_command';
      end;
      v_target_player_id := v_payload ->> 'player_id';
      if v_target_player_id is null
        or v_target_player_id !~ '^[A-Za-z0-9][A-Za-z0-9._:-]{0,127}$'
        or jsonb_typeof(coalesce(v_payload -> 'scopes', '[]'::jsonb)) <> 'array'
        or exists (
          select 1
          from jsonb_array_elements(coalesce(v_payload -> 'scopes', '[]'::jsonb)) as item(value)
          where jsonb_typeof(item.value) <> 'string'
        )
      then
        raise exception using errcode = 'P0001', message = 'universe_invalid_command';
      end if;
      select coalesce(
        array_agg(item.value #>> '{}' order by item.value #>> '{}'),
        array[]::text[]
      )
        into v_target_scopes
      from jsonb_array_elements(coalesce(v_payload -> 'scopes', '[]'::jsonb)) as item(value);
      if '*' = any (v_target_scopes)
        or exists (
          select 1
          from unnest(v_target_scopes) as granted_scope(value)
          where granted_scope.value !~ '^[a-z][a-z0-9_.-]*:[a-z][a-z0-9_.-]*$'
        )
        or (not v_is_owner and not (v_target_scopes <@ v_scopes))
      then
        raise exception using errcode = 'P0001', message = 'universe_forbidden';
      end if;
      insert into public.universe_memberships (
        realm_id, user_id, membership_id, player_id, status, scopes, metadata,
        created_at, updated_at
      ) values (
        v_realm_id, v_target_user_id, v_stream_id, v_target_player_id,
        'invited', v_target_scopes, '{}'::jsonb, v_occurred_at, v_occurred_at
      )
      on conflict (realm_id, user_id) do update
      set membership_id = excluded.membership_id,
          player_id = excluded.player_id,
          status = 'invited',
          scopes = excluded.scopes,
          metadata = excluded.metadata,
          updated_at = excluded.updated_at
      where public.universe_memberships.status = 'removed';
      get diagnostics v_rows = row_count;
      if v_rows <> 1 then
        raise exception using errcode = 'P0001', message = 'universe_invalid_command';
      end if;
      v_payload := v_payload || jsonb_build_object('status', 'invited');
    elsif v_command_type = 'membership.accept' then
      update public.universe_memberships
      set status = 'active', updated_at = v_occurred_at
      where realm_id = v_realm_id
        and user_id = v_user_id
        and membership_id = v_stream_id
        and status = 'invited';
      get diagnostics v_rows = row_count;
      if v_rows <> 1 then
        raise exception using errcode = 'P0001', message = 'universe_forbidden';
      end if;
      v_payload := v_payload || jsonb_build_object('status', 'active');
    end if;

    update public.universe_realms
    set version = version + 1, updated_at = v_occurred_at
    where realm_id = v_realm_id;
  end if;

  v_sequence := nextval(pg_get_serial_sequence('public.universe_events', 'sequence'));
  v_authorization := jsonb_build_object(
    'allowed', true,
    'reason', case when v_is_owner then 'authenticated realm owner' else 'active realm membership' end,
    'scopes', to_jsonb(v_scopes),
    'owner_gate', case when v_needs_approval then 'consumed' else 'not_required' end
  );
  v_provenance := jsonb_build_object(
    'source', 'supabase_authenticated_user',
    'evidence', jsonb_build_array('auth:verified'),
    'confidence', 1.0,
    'signature', null
  );
  v_entity := coalesce(v_current_entity, '{}'::jsonb)
    || v_payload
    || jsonb_build_object(
      'id', v_stream_id,
      'entity_type', v_stream_type,
      'realm_id', v_realm_id,
      'version', v_current_version + 1,
      'updated_at', v_occurred_at,
      'simulation', v_simulation
    );
  v_event := jsonb_build_object(
    'sequence', v_sequence,
    'event_id', v_event_id,
    'schema_version', 1,
    'event_type', v_event_type,
    'realm_id', v_realm_id,
    'actor_id', v_actor_id,
    'stream_type', v_stream_type,
    'stream_id', v_stream_id,
    'stream_version', v_current_version + 1,
    'authorization', case when v_is_public then jsonb_build_object(
      'allowed', true,
      'reason', 'authorized public submission',
      'scopes', '[]'::jsonb,
      'owner_gate', v_authorization -> 'owner_gate'
    ) else v_authorization end,
    'causation_id', v_causation_id,
    'correlation_id', v_correlation_id,
    'occurred_at', v_occurred_at,
    'payload', v_payload,
    'provenance', v_provenance,
    'simulation', v_simulation,
    'rollback', case when v_is_public then '{}'::jsonb
      else coalesce(v_current_entity, '{}'::jsonb) end
  );

  insert into public.universe_events (
    sequence, event_id, schema_version, event_type, realm_id,
    actor_user_id, actor_id, stream_type, stream_id, stream_version,
    authorization, causation_id, correlation_id, occurred_at, payload,
    provenance, simulation, rollback, is_public, event
  ) values (
    v_sequence, v_event_id, 1, v_event_type, v_realm_id,
    v_user_id, v_actor_id, v_stream_type, v_stream_id, v_current_version + 1,
    v_authorization, v_causation_id, v_correlation_id, v_occurred_at, v_payload,
    v_provenance, v_simulation, coalesce(v_current_entity, '{}'::jsonb),
    v_is_public, v_event
  );

  insert into public.universe_entities (
    realm_id, entity_type, entity_id, version, is_public, deleted,
    updated_at, entity
  ) values (
    v_realm_id, v_stream_type, v_stream_id, v_current_version + 1,
    v_is_public,
    case when v_payload ? 'deleted' then (v_payload ->> 'deleted')::boolean else false end,
    v_occurred_at, v_entity
  )
  on conflict (realm_id, entity_type, entity_id) do update
  set version = excluded.version,
      is_public = excluded.is_public,
      deleted = excluded.deleted,
      updated_at = excluded.updated_at,
      entity = excluded.entity
  where public.universe_entities.version = v_current_version;
  get diagnostics v_rows = row_count;
  if v_rows <> 1 then
    raise exception using
      errcode = 'P0001',
      message = 'universe_version_conflict',
      detail = jsonb_build_object(
        'error', 'MUSE_VERSION_CONFLICT',
        'expected_version', v_expected_version,
        'current_version', v_current_version
      )::text;
  end if;

  v_result := jsonb_build_object(
    'event', v_event,
    'entity', v_entity,
    'idempotent_replay', false
  );
  insert into public.universe_command_results (
    realm_id, command_id, actor_user_id, command_fingerprint,
    event_id, result, created_at
  ) values (
    v_realm_id, v_command_id, v_user_id, v_command_fingerprint,
    v_event_id, v_result, v_occurred_at
  );
  return v_result;
end;
$$;

revoke all on function public.execute_universe_command(jsonb) from public;
revoke execute on function public.execute_universe_command(jsonb) from anon;
grant execute on function public.execute_universe_command(jsonb) to authenticated;
