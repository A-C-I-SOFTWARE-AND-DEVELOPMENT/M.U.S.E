create or replace function public.universe_json_has_forbidden_keys(p_value jsonb)
returns boolean
language plpgsql
immutable
set search_path = pg_catalog, public
as $$
declare
  item record;
  normalized text;
begin
  if jsonb_typeof(p_value) = 'object' then
    for item in select key, value from jsonb_each(p_value)
    loop
      normalized := lower(regexp_replace(item.key, '[^a-zA-Z0-9]+', '', 'g'));
      if normalized in (
        'apikey', 'authorization', 'ownerauthorization', 'ownerphrase',
        'privatekey', 'providerkey', 'token'
      ) or normalized ~ '(bearer|cookie|credential|password|passwd|secret)'
        or normalized ~ 'token$'
      then
        return true;
      end if;
      if public.universe_json_has_forbidden_keys(item.value) then
        return true;
      end if;
    end loop;
  elsif jsonb_typeof(p_value) = 'array' then
    for item in select value from jsonb_array_elements(p_value)
    loop
      if public.universe_json_has_forbidden_keys(item.value) then
        return true;
      end if;
    end loop;
  end if;
  return false;
end;
$$;

