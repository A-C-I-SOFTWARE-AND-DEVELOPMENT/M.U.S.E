-- Authoritative M.U.S.E network-realm event log, projections, and command RPC.
-- Clients can read only through tenant-safe RLS and can write only through the
-- authenticated execute_universe_command transaction below.

create schema if not exists extensions;
create extension if not exists pgcrypto with schema extensions;

create table if not exists public.universe_realms (
  realm_id text primary key,
  owner_user_id uuid not null references auth.users (id) on delete restrict,
  name text not null check (char_length(name) between 1 and 200),
  mode text not null check (mode in ('private', 'team', 'network', 'public')),
  is_public boolean not null default false,
  version bigint not null default 0 check (version >= 0),
  metadata jsonb not null default '{}'::jsonb check (jsonb_typeof(metadata) = 'object'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.universe_memberships (
  realm_id text not null references public.universe_realms (realm_id) on delete restrict,
  user_id uuid not null references auth.users (id) on delete restrict,
  membership_id text not null,
  player_id text not null,
  status text not null check (status in ('invited', 'active', 'removed')),
  scopes text[] not null default array[]::text[] check (cardinality(scopes) <= 64),
  metadata jsonb not null default '{}'::jsonb check (jsonb_typeof(metadata) = 'object'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (realm_id, user_id),
  unique (membership_id),
  unique (realm_id, player_id)
);

create table if not exists public.universe_events (
  sequence bigint generated by default as identity primary key,
  event_id text not null unique default gen_random_uuid()::text,
  schema_version integer not null default 1 check (schema_version = 1),
  event_type text not null,
  realm_id text not null references public.universe_realms (realm_id) on delete restrict,
  actor_user_id uuid not null references auth.users (id) on delete restrict,
  actor_id text not null,
  stream_type text not null,
  stream_id text not null,
  stream_version bigint not null check (stream_version > 0),
  authorization jsonb not null check (jsonb_typeof(authorization) = 'object'),
  causation_id text not null,
  correlation_id text not null,
  occurred_at timestamptz not null,
  payload jsonb not null check (jsonb_typeof(payload) = 'object'),
  provenance jsonb not null check (jsonb_typeof(provenance) = 'object'),
  simulation boolean not null default false,
  rollback jsonb not null check (jsonb_typeof(rollback) = 'object'),
  is_public boolean not null default false,
  event jsonb not null check (jsonb_typeof(event) = 'object'),
  unique (stream_type, stream_id, stream_version)
);

create index if not exists universe_events_realm_sequence
  on public.universe_events (realm_id, sequence);
create index if not exists universe_events_realm_stream
  on public.universe_events (realm_id, stream_type, stream_id, stream_version);

create table if not exists public.universe_entities (
  realm_id text not null references public.universe_realms (realm_id) on delete restrict,
  entity_type text not null,
  entity_id text not null,
  version bigint not null check (version > 0),
  is_public boolean not null default false,
  deleted boolean not null default false,
  updated_at timestamptz not null,
  entity jsonb not null check (jsonb_typeof(entity) = 'object'),
  primary key (realm_id, entity_type, entity_id)
);

create index if not exists universe_entities_realm_type
  on public.universe_entities (realm_id, entity_type, entity_id);

create table if not exists public.universe_command_results (
  realm_id text not null references public.universe_realms (realm_id) on delete restrict,
  command_id text not null,
  actor_user_id uuid not null references auth.users (id) on delete restrict,
  command_fingerprint text not null check (command_fingerprint ~ '^[0-9a-f]{64}$'),
  event_id text not null references public.universe_events (event_id) on delete restrict,
  result jsonb not null check (jsonb_typeof(result) = 'object'),
  created_at timestamptz not null default now(),
  primary key (realm_id, command_id)
);

-- Bound approvals are service-authored records consumed atomically by the RPC.
-- No browser or authenticated client role receives direct write access.
create table if not exists public.universe_approval_grants (
  approval_id text primary key,
  realm_id text not null references public.universe_realms (realm_id) on delete restrict,
  actor_user_id uuid not null references auth.users (id) on delete restrict,
  action text not null,
  correlation_id text not null,
  subject_hash text not null check (subject_hash ~ '^[0-9a-f]{64}$'),
  state text not null check (state in ('approved', 'consumed', 'revoked')),
  expires_at timestamptz not null,
  created_at timestamptz not null default now(),
  consumed_at timestamptz
);

create index if not exists universe_approvals_realm_actor
  on public.universe_approval_grants (realm_id, actor_user_id, state, expires_at);

